/** French puts a non-breaking space before these, so they never start a line, and inside a number like 1 500. */
const typography = (text: string) =>
  text
    .replace(/ ([:%$»])/g, '\u00a0$1')
    .replace(/« /g, '«\u00a0')
    .replace(/(\d) (\d{3})(?!\d)/g, '$1\u00a0$2');

